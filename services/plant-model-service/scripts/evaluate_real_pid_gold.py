"""Independent human-reference gating for real P&ID extraction.

No gold labels are generated by an AI extraction pipeline. Engineers annotate
from original drawings and must mark each sheet complete and reviewed.
A second engineer must sign the sheet before performance figures can be
computed. Unreviewed or unmatched-source sheets are NOT scored.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def _measure(actual: set, truth: set) -> dict[str, Any]:
    tp = len(actual & truth)
    fp = len(actual - truth)
    fn = len(truth - actual)
    precision = tp/(tp+fp) if tp+fp else (1.0 if not truth else 0.0)
    recall = tp/(tp+fn) if tp+fn else 1.0
    return {
        "TP":tp, "FP":fp, "FN":fn,
        "precision":round(precision,4), "recall":round(recall,4),
        "f1":round(2*precision*recall/(precision+recall),4)
        if precision+recall else 0.0,
    }


def assess_annotated_evidence(tasks: dict, evidence: dict) -> dict:
    """Score tag identities and undirected graph edges only on signed sheets.

    Symbol bounding-box metrics require manually annotated rectangles and
    geometry matching; not computed by this function.
    """
    if tasks.get("source_sha256") != evidence.get("source_sha256"):
        raise ValueError("Gold references do not match the original drawing")
    true_by_page = {t["source_pdf_page"]:t for t in tasks.get("tasks", [])}
    predictions = {s["original_source_page"]:s for s in evidence.get("sheets", [])}
    results = []
    pending = []
    for page, record in sorted(predictions.items()):
        gold=true_by_page.get(page)
        if not gold:
            pending.append({"page":page,"reason":"no engineer reference"})
            continue
        if (gold.get("annotation_status")!="independently_verified"
            or not gold.get("annotator")
            or not gold.get("independent_second_reviewer")
            or gold["annotator"]==gold["independent_second_reviewer"]):
            pending.append({"page":page,"reason":"two independent engineering reviews missing"})
            continue
        # Source hashes are full-file and, if supplied, must match exactly.
        if gold.get("source_pdf_sha256")!=evidence.get("source_sha256"):
            raise ValueError(f"Gold page {page} has inconsistent source SHA")
        expected_tags={t["tag"] for t in gold["confirmed_tags"]}
        found_tags={t["tag"] for t in record["tags"]}
        actual_edges={
            tuple(sorted((edge["source_tag"],edge["target_tag"])))
            for edge in record["connection_hypotheses"]
        }
        true_edges={
            tuple(sorted((edge["source_tag"],edge["target_tag"])))
            for edge in gold["confirmed_connections"]
        }
        results.append({
            "page":page,
            "tag_identity":_measure(found_tags,expected_tags),
            "undirected_connection_identity":_measure(actual_edges,true_edges),
            "symbol_bbox_accuracy":"NOT_COMPUTED",
            "notes":"Tag/graph identity alone cannot validate source geometry or engineering interpretation.",
        })
    return {
        "source_sha256":evidence.get("source_sha256"),
        "verified_sheets_scored":len(results),
        "unverified_sheets":pending,
        "results":results,
        "industrial_accuracy_claim_allowed":len(results)==len(predictions)
        and len(predictions)>=10,
        "caution":"Requires independent review, full bbox validation and representative drawing corpus before industrial claims.",
    }


def main() -> None:
    import argparse
    parser=argparse.ArgumentParser()
    parser.add_argument("--gold",type=Path,required=True)
    parser.add_argument("--evidence",type=Path,required=True)
    parser.add_argument("--out",type=Path,required=True)
    args=parser.parse_args()
    result=assess_annotated_evidence(
        json.loads(args.gold.read_text()),json.loads(args.evidence.read_text()))
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(result,indent=2))
    print(json.dumps({
        "scored":result["verified_sheets_scored"],
        "pending":len(result["unverified_sheets"]),
        "accuracy_claim_allowed":result["industrial_accuracy_claim_allowed"],
    },indent=2))


if __name__=="__main__":
    main()
